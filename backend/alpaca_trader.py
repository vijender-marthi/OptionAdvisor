# OCC SYMBOL BUILDER
# ─────────────────────────────────────────────────────────────

def build_occ_symbol(ticker: str, expiry: str, option_type: str, strike: float) -> str:
    """
    Build the OCC option symbol used by Alpaca.
    ticker:      e.g. "AAPL"
    expiry:      "YYYY-MM-DD"
    option_type: "CALL" or "PUT"
    strike:      e.g. 190.0

    Output: "AAPL240119C00190000"
    """
    dt  = datetime.strptime(expiry, "%Y-%m-%d")
    ymd = dt.strftime("%y%m%d")                        # 6-digit YYMMDD
    cp  = "C" if option_type.upper() == "CALL" else "P"
    # Strike in thousandths, zero-padded to 8 digits
    strike_int = int(round(strike * 1000))
    strike_str = str(strike_int).zfill(8)
    return f"{ticker.upper()}{ymd}{cp}{strike_str}"


