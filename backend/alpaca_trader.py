"""
alpaca_trader.py — Alpaca Paper Trading Integration
====================================================
Connects to Alpaca's Paper Trading API to place multi-leg options orders
generated by the OptionAdvisor engine.

API docs: https://docs.alpaca.markets/reference/getallorders
Paper base URL: https://paper-api.alpaca.markets

OCC Symbol format: TICKER + YYMMDD + C/P + 8-digit strike (thousandths, zero-padded)
  Example: AAPL 190.0 CALL 2024-01-19 → AAPL240119C00190000
"""

import os
import re
from datetime import datetime
from pathlib import Path
from typing import Optional

import httpx
from dotenv import load_dotenv

# ─────────────────────────────────────────────────────────────
# CONFIG
# ─────────────────────────────────────────────────────────────

ALPACA_PAPER_BASE = "https://paper-api.alpaca.markets"
ALPACA_DATA_BASE  = "https://data.alpaca.markets"

def _get_creds() -> tuple[str, str]:
    # Same directory as main.py .env — reload so edits apply without restarting (local dev).
    load_dotenv(Path(__file__).with_name(".env"), override=True)
    key    = os.getenv("ALPACA_API_KEY", "").strip()
    secret = os.getenv("ALPACA_SECRET_KEY", "").strip()
    return key, secret

def _headers() -> dict:
    key, secret = _get_creds()
    return {
        "APCA-API-KEY-ID":     key,
        "APCA-API-SECRET-KEY": secret,
        "Content-Type":        "application/json",
        "Accept":              "application/json",
    }

def is_configured() -> bool:
    key, secret = _get_creds()
    return bool(key and secret)


