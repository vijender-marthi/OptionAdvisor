def get_account() -> dict:
    """Return Alpaca paper account details (cash, buying power, equity, etc.)."""
    if not is_configured():
        return {"error": "Alpaca API keys not configured"}
    try:
        r = httpx.get(f"{ALPACA_PAPER_BASE}/v2/account", headers=_headers(), timeout=10)
        r.raise_for_status()
        d = r.json()
        return {
            "status":         d.get("status"),
            "equity":         float(d.get("equity", 0)),
            "cash":           float(d.get("cash", 0)),
            "buying_power":   float(d.get("options_buying_power") or d.get("buying_power", 0)),
            "day_trade_count": int(d.get("daytrade_count", 0)),
            "options_approved_level": int(d.get("options_approved_level", 0)),
            "pattern_day_trader": d.get("pattern_day_trader", False),
            "currency":       d.get("currency", "USD"),
        }
    except httpx.HTTPStatusError as e:
        return {"error": f"Alpaca API error {e.response.status_code}: {e.response.text}"}
    except Exception as e:
        return {"error": str(e)}


