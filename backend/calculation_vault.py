def _decode_row(row: sqlite3.Row | None) -> dict[str, Any] | None:
    if row is None:
        return None
    data = dict(row)
    for key in ("input_json", "output_json", "metric_definitions_json", "event_json", "definition_json"):
        if key in data:
            try:
                data[key[:-5] if key.endswith("_json") else key] = json.loads(data[key] or "{}")
            except (TypeError, json.JSONDecodeError):
                data[key[:-5] if key.endswith("_json") else key] = {} if key != "metric_definitions_json" else []
            data.pop(key, None)
    return data


def get_calculation_run(run_id: str, owner_email: str | None = None) -> dict[str, Any] | None:
    with _connect() as conn:
        ensure_calculation_vault_schema(conn)
        if owner_email is None:
            row = conn.execute(
                "SELECT * FROM calculation_runs WHERE run_id = ?",
                (run_id.strip(),),
            ).fetchone()
        else:
            row = conn.execute(
                "SELECT * FROM calculation_runs WHERE run_id = ? AND owner_email = ?",
                (run_id.strip(), _normalize_owner_email(owner_email)),
            ).fetchone()
    return _decode_row(row)


def get_calculation_snapshot(snapshot_id: str, owner_email: str | None = None) -> dict[str, Any] | None:
    with _connect() as conn:
        ensure_calculation_vault_schema(conn)
        if owner_email is None:
            row = conn.execute(
                "SELECT * FROM calculation_snapshots WHERE snapshot_id = ?",
                (snapshot_id.strip(),),
            ).fetchone()
        else:
            row = conn.execute(
                "SELECT * FROM calculation_snapshots WHERE snapshot_id = ? AND owner_email = ?",
                (snapshot_id.strip(), _normalize_owner_email(owner_email)),
            ).fetchone()
    return _decode_row(row)


def verify_calculation_snapshot(snapshot_id: str, owner_email: str | None = None) -> dict[str, Any] | None:
    """Recompute stored snapshot hashes and verify run/snapshot linkage."""
    snapshot = get_calculation_snapshot(snapshot_id, owner_email=owner_email)
    if snapshot is None:
        return None

    run = get_calculation_run(str(snapshot.get("run_id") or ""), owner_email=owner_email)
    computed_input_hash = sha256_json(snapshot.get("input") or {})
    computed_output_hash = sha256_json(snapshot.get("output") or {})
    stored_input_hash = str(snapshot.get("input_hash") or "")
    stored_output_hash = str(snapshot.get("output_hash") or "")
    input_hash_matches = computed_input_hash == stored_input_hash
    output_hash_matches = computed_output_hash == stored_output_hash
    run_hash_matches = bool(
        run
        and str(run.get("input_hash") or "") == stored_input_hash
        and str(run.get("output_hash") or "") == stored_output_hash
        and str(run.get("snapshot_id") or "") == str(snapshot.get("snapshot_id") or "")
    )

    mismatches: list[str] = []
    if not input_hash_matches:
        mismatches.append("input_hash")
    if not output_hash_matches:
        mismatches.append("output_hash")
    if not run_hash_matches:
        mismatches.append("run_snapshot_link")

    return {
        "snapshot_id": snapshot["snapshot_id"],
        "run_id": snapshot["run_id"],
        "verified": input_hash_matches and output_hash_matches and run_hash_matches,
        "input_hash_matches": input_hash_matches,
        "output_hash_matches": output_hash_matches,
        "run_hash_matches": run_hash_matches,
        "stored_input_hash": stored_input_hash,
        "computed_input_hash": computed_input_hash,
        "stored_output_hash": stored_output_hash,
        "computed_output_hash": computed_output_hash,
        "mismatches": mismatches,
        "verified_at_ms": now_ms(),
    }


def list_calculation_snapshot_audit_log(snapshot_id: str, owner_email: str | None = None) -> list[dict[str, Any]] | None:
    """Return audit events for a snapshot, scoped through the owning snapshot row."""
    snapshot = get_calculation_snapshot(snapshot_id, owner_email=owner_email)
    if snapshot is None:
        return None

    with _connect() as conn:
        ensure_calculation_vault_schema(conn)
        rows = conn.execute(
            """
            SELECT *
            FROM calculation_snapshot_audit_log
            WHERE snapshot_id = ?
            ORDER BY created_at_ms ASC
            """,
            (snapshot_id.strip(),),
        ).fetchall()
    return [decoded for row in rows if (decoded := _decode_row(row)) is not None]


def list_calculation_runs(
    *,
    owner_email: str | None = None,
    status: str | None = None,
    run_type: str | None = None,
    limit: int = 50,
) -> list[dict[str, Any]]:
    clauses: list[str] = []
    params: list[Any] = []
    if owner_email is not None:
        clauses.append("owner_email = ?")
        params.append(_normalize_owner_email(owner_email))
    if status:
        clauses.append("status = ?")
        params.append(status.strip().upper())
    if run_type:
        clauses.append("run_type = ?")
        params.append(run_type.strip().lower())
    where = f"WHERE {' AND '.join(clauses)}" if clauses else ""
    params.append(max(1, min(200, int(limit))))
    with _connect() as conn:
        ensure_calculation_vault_schema(conn)
        rows = conn.execute(
            f"""
            SELECT *
            FROM calculation_runs
            {where}
            ORDER BY created_at_ms DESC
            LIMIT ?
            """,
            params,
        ).fetchall()
    return [decoded for row in rows if (decoded := _decode_row(row)) is not None]


def list_metric_definitions() -> list[dict[str, Any]]:
    with _connect() as conn:
        ensure_calculation_vault_schema(conn)
        rows = conn.execute(
            """
            SELECT definition_json
            FROM metric_definitions
            ORDER BY metric_id ASC, formula_version ASC
            """
        ).fetchall()
    out: list[dict[str, Any]] = []
    for row in rows:
        try:
            value = json.loads(row["definition_json"] or "{}")
            if isinstance(value, dict):
                out.append(value)
        except (TypeError, json.JSONDecodeError):
            continue
    return out
