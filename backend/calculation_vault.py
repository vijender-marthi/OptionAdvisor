def create_calculation_snapshot(
    *,
    run_type: str,
    input_payload: dict[str, Any],
    output_payload: dict[str, Any],
    engine_version: str,
    owner_email: str | None = None,
    formula_pack_version: str = CURRENT_FORMULA_PACK_VERSION,
    metric_definitions_version: str = CURRENT_METRIC_DEFINITIONS_VERSION,
    metric_definitions: list[dict[str, Any]] | None = None,
) -> dict[str, Any]:
    """Insert a completed run and immutable snapshot. Never updates existing rows."""
    run_id = str(uuid.uuid4())
    snapshot_id = str(uuid.uuid4())
    created = now_ms()
    input_hash = sha256_json(input_payload)
    output_hash = sha256_json(output_payload)
    metric_defs = metric_definitions if metric_definitions is not None else DEFAULT_METRIC_DEFINITIONS
    owner = _normalize_owner_email(owner_email)
    with _connect() as conn:
        ensure_calculation_vault_schema(conn)
        conn.execute(
            """
            INSERT INTO calculation_runs (
                run_id, run_type, status, engine_version, formula_pack_version,
                owner_email, input_hash, output_hash, snapshot_id, input_json,
                created_at_ms, completed_at_ms
            ) VALUES (?, ?, 'COMPLETED', ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                run_id,
                run_type,
                engine_version,
                formula_pack_version,
                owner,
                input_hash,
                output_hash,
                snapshot_id,
                canonical_json(input_payload),
                created,
                created,
            ),
        )
        conn.execute(
            """
            INSERT INTO calculation_snapshots (
                snapshot_id, run_id, run_type, engine_version, formula_pack_version,
                metric_definitions_version, owner_email, input_hash, output_hash,
                input_json, output_json, metric_definitions_json,
                created_at_ms, frozen_at_ms
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                snapshot_id,
                run_id,
                run_type,
                engine_version,
                formula_pack_version,
                metric_definitions_version,
                owner,
                input_hash,
                output_hash,
                canonical_json(input_payload),
                canonical_json(output_payload),
                canonical_json(metric_defs),
                created,
                created,
            ),
        )
        conn.execute(
            """
            INSERT INTO calculation_snapshot_audit_log (
                audit_id, snapshot_id, event_type, event_json, created_at_ms
            ) VALUES (?, ?, 'SNAPSHOT_FROZEN', ?, ?)
            """,
            (
                str(uuid.uuid4()),
                snapshot_id,
                canonical_json({"runId": run_id, "ownerEmail": owner, "inputHash": input_hash, "outputHash": output_hash}),
                created,
            ),
        )
    loaded = get_calculation_snapshot(snapshot_id)
    assert loaded is not None
    return loaded


